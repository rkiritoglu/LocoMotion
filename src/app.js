// Render Route Cards
function renderRouteCards(routes) {
  const container = document.getElementById("routes-grid");
  if (!container) return;

  container.innerHTML = routes.map(route => `
    <article class="route-card" onclick="openRouteArticle('${route.id}')">
      <div class="card-img-wrap">
        <img class="card-img" src="${route.heroImage}" alt="${route.title}" onerror="this.onerror=null; this.src='${route.fallbackHero || ''}';">
        <span class="card-badge">${route.category}</span>
      </div>
      <div class="card-body">
        <span class="card-country">📍 ${route.country}</span>
        <h3 class="card-title">${route.title}</h3>
        <p class="card-excerpt">${route.excerpt}</p>
        <div class="card-footer">
          <span>⏱️ ${route.duration} • 🛤️ ${route.distance}</span>
          <span class="card-read-link">Keşfet &rarr;</span>
        </div>
      </div>
    </article>
  `).join("");
}

// Setup Category Filters
function setupFilterListeners() {
  const buttons = document.querySelectorAll(".filter-btn");
  buttons.forEach(btn => {
    btn.addEventListener("click", () => {
      buttons.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      const filter = btn.getAttribute("data-filter");

      if (filter === "all") {
        renderRouteCards(routesData);
      } else {
        const filtered = routesData.filter(r => 
          r.category === filter || (r.tags && r.tags.includes(filter))
        );
        renderRouteCards(filtered);
      }
    });
  });
}

// Interactive Leaflet Map
function initMap() {
  const mapElement = document.getElementById("rail-map");
  if (!mapElement) return;

  mapInstance = L.map("rail-map", {
    center: [52.0, 5.0],
    zoom: 5,
    scrollWheelZoom: false
  });

  const osmStandard = L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
    maxZoom: 19,
    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright" target="_blank">OpenStreetMap</a> Katkıda Bulunanlar'
  });

  const openTopo = L.tileLayer("https://{s}.tile.opentopomap.org/{z}/{x}/{y}.png", {
    maxZoom: 17,
    attribution: 'Harita: &copy; <a href="https://opentopomap.org" target="_blank">OpenTopoMap</a>'
  });

  const railwayLayer = L.tileLayer("https://{s}.tiles.openrailwaymap.org/standard/{z}/{x}/{y}.png", {
    maxZoom: 19,
    attribution: 'Demiryolu Ağı: &copy; <a href="https://www.openrailwaymap.org" target="_blank">OpenRailwayMap</a>'
  });

  osmStandard.addTo(mapInstance);
  railwayLayer.addTo(mapInstance);

  const baseMaps = {
    "🗺️ OpenStreetMap (Standart)": osmStandard,
    "🏔️ OpenTopoMap (Dağ & Arazi)": openTopo
  };

  const overlayMaps = {
    "🚂 Gerçek Ray Hatları (OpenRailwayMap)": railwayLayer
  };

  L.control.layers(baseMaps, overlayMaps, { position: "topright" }).addTo(mapInstance);

  // Plot all stops for all routes
  routesData.forEach(route => {
    if (!route.coordinates) return;
    const polylineCoords = [];

    route.coordinates.forEach(point => {
      polylineCoords.push([point.lat, point.lng]);

      const marker = L.circleMarker([point.lat, point.lng], {
        radius: 7,
        fillColor: route.id === "jacobite-steam-train" ? "#c8963e" : (route.id === "bernina-express" ? "#dc2626" : "#2563eb"),
        color: "#153230",
        weight: 2,
        opacity: 1,
        fillOpacity: 0.95
      }).addTo(mapInstance);

      marker.bindPopup(`
        <div style="font-family: 'Plus Jakarta Sans', sans-serif;">
          <strong style="color: #153230; font-size: 14px;">${point.name}</strong>
          <p style="margin: 4px 0 0; font-size: 12px; color: #5e6d75;">${point.desc}</p>
          <button style="margin-top: 6px; padding: 4px 8px; font-size: 11px; background: #c8963e; color: #fff; border: none; border-radius: 4px; cursor: pointer;" onclick="openRouteArticle('${route.id}')">Yazıyı Oku</button>
        </div>
      `);
    });

    L.polyline(polylineCoords, {
      color: route.id === "jacobite-steam-train" ? "#c8963e" : (route.id === "bernina-express" ? "#dc2626" : "#2563eb"),
      weight: 4,
      dashArray: "8, 6",
      opacity: 0.85
    }).addTo(mapInstance);
  });
}

function parseMarkdownSafe(mdText) {
  if (window.marked && typeof window.marked.parse === "function") {
    return window.marked.parse(mdText);
  }
  return mdText
    .replace(/^# (.*$)/gim, '<h1>$1</h1>')
    .replace(/^## (.*$)/gim, '<h2>$1</h2>')
    .replace(/^### (.*$)/gim, '<h3>$1</h3>')
    .replace(/^\> (.*$)/gim, '<blockquote>$1</blockquote>')
    .replace(/\!\[(.*?)\]\((.*?)\)/gim, '<img alt="$1" src="$2" />')
    .replace(/\n\*(.*?)\*\n/gim, '<p><em>$1</em></p>')
    .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/gim, '<em>$1</em>')
    .replace(/\n\n/gim, '<br/><br/>');
}

// Open Route Article Page (Normal Web Sayfası Olarak Aşağı Uzayan Görünüm)
async function openRouteArticle(routeId) {
  const route = routesData.find(r => r.id === routeId);
  const hero = document.querySelector(".hero-section");
  const mainGrid = document.getElementById("rotalar");
  const articlePage = document.getElementById("article-page");
  const body = document.getElementById("article-body");
  const navCategory = document.getElementById("article-nav-category");

  if (!route || !articlePage || !body) return;

  if (navCategory) {
    navCategory.innerText = `${route.category || 'Demiryolu Rotası'} • ${route.country || ''}`;
  }

  let loadedContent = route.content || "";

  if (route.markdownPath) {
    try {
      const response = await fetch(route.markdownPath);
      if (response.ok) {
        let text = await response.text();
        if (!text.includes("<!DOCTYPE") && !text.includes("<html")) {
          loadedContent = text.replace(/^---[\s\S]*?---\n/, "");
        }
      }
    } catch (err) {
      console.warn("Using embedded fallback:", err);
    }
  }

  if (loadedContent) {
    let processedContent = loadedContent.replace(/!\[(.*?)\]\(images\//g, `![$1](content/routes/${routeId}/images/`);
    body.innerHTML = parseMarkdownSafe(processedContent);
  } else {
    body.innerHTML = `
      <div style="text-align: center; padding: 40px 0;">
        <span style="font-size: 3rem;">🚂</span>
        <h1 style="font-family: 'Playfair Display', serif; margin-top: 16px;">${route.title}</h1>
        <p style="color: #5e6d75; max-width: 600px; margin: 16px auto;">Bu rota günlüğü hazırlanıyor. Çok yakında yayında!</p>
      </div>
    `;
  }

  // Switch to Article Full Web Page view (hide hero and routes list)
  if (hero) hero.classList.add("hidden");
  if (mainGrid) mainGrid.classList.add("hidden");
  articlePage.classList.remove("hidden");

  // Keep body overflow normal so page extends and scrolls naturally downwards
  document.body.style.overflow = "auto";

  // Update hash for deep link and browser back/forward buttons
  if (window.location.hash !== "#rota-" + routeId) {
    window.location.hash = "rota-" + routeId;
  }

  // Update nav link active state
  document.querySelectorAll(".nav-item").forEach(item => item.classList.remove("active"));

  // Smooth scroll to top of page
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function showHomeView() {
  const hero = document.querySelector(".hero-section");
  const mainGrid = document.getElementById("rotalar");
  const articlePage = document.getElementById("article-page");

  if (articlePage) articlePage.classList.add("hidden");
  if (hero) hero.classList.remove("hidden");
  if (mainGrid) mainGrid.classList.remove("hidden");

  // Reset hash if it was a route hash
  if (window.location.hash.startsWith("#rota-")) {
    history.pushState(null, "", window.location.pathname + window.location.search);
  }

  document.querySelectorAll(".nav-item").forEach(item => item.classList.remove("active"));
  const routesLink = document.querySelector('a[href="#rotalar"]');
  if (routesLink) routesLink.classList.add("active");

  window.scrollTo({ top: 0, behavior: "smooth" });
}

